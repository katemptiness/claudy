CANVAS_ROW, CANVAS_COL = 3, 25

# Each picture is painted in three stages: (brush position, paint, canvas).
# The last stage's canvas is the finished picture.
PICTURES = {
    "landscape": (
        ("up", "u", "uuuuu uuuuu ccccc ccccc ccccc"),
        ("up", "y", "uuuyu uuuuu uuuuu ccccc ccccc"),
        ("down", "n", "uuuyu uuuuu uuuuu nnuuu nnnnn"),
    ),
    "flower": (
        ("down", "n", "ccccc ccccc ccncc cnncc ccncc"),
        ("up", "k", "ckkkc kkckk ckkkc cnncc ccncc"),
        ("up", "y", "ckkkc kkykk ckkkc cnncc ccncc"),
    ),
    "heart": (
        ("up", "r", "crccc rrrcc rrrcc crrcc ccrcc"),
        ("up", "r", "crcrc rrrrr rrrrr crrrc ccrcc"),
        ("up", "k", "crcrc rkrrr rrrrr crrrc ccrcc"),
    ),
    "friend": (
        ("up", "u", "ccccc cuuuc cuuuc cuuuc ccccc"),
        ("down", "u", "ccccc cuuuc uuuuu cuuuc cucuc"),
        ("up", "e", "ccccc cuuuc ueueu cuuuc cucuc"),
    ),
}


def painting(base, canvas, paint="c"):
    """A painter pose with `canvas` (5 rows, space-separated) on the easel
    and `paint` on the brush."""
    rows = [list(row) for row in base]
    for r, line in enumerate(canvas.split()):
        rows[CANVAS_ROW + r][CANVAS_COL:CANVAS_COL + 5] = sprite(line)[0]
    tip, color = SYMBOLS["o"], SYMBOLS[paint]
    return [[color if v == tip else v for v in row] for row in rows]


def painting_sprites():
    """paint_setup, then per picture: paint_<picture>_<stage>_a/_b while
    painting each stage, and paint_<picture>_done."""
    sprites = {"paint_setup": painting(PAINT_REST, " ".join(["ccccc"] * 5))}
    for picture, stages in PICTURES.items():
        for n, (brush, paint, canvas) in enumerate(stages, 1):
            pose = PAINT_UP if brush == "up" else PAINT_DOWN
            sprites[f"paint_{picture}_{n}_a"] = painting(pose, canvas, paint)
            sprites[f"paint_{picture}_{n}_b"] = painting(PAINT_MID, canvas, paint)
        sprites[f"paint_{picture}_done"] = painting(PAINT_REST, stages[-1][2])
    return sprites


